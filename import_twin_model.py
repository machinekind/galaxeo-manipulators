#!/usr/bin/env python3
"""Generate the digital twin's A1X model (`galaxeo/robot/a1x/a1x.xml`) from the vendor URDF.

    python import_twin_model.py                       # rebuild galaxeo/robot/a1x/a1x.xml
    python import_twin_model.py --out /tmp/a1x.xml    # the same, elsewhere, to compare

The same deterministic path as `sim/urdf2mjcf.py` (ElementTree + minidom), plus six rules the
twin needs. They are also listed in the header of the generated file:

1. Joint `gripper_finger_joint1` is named `gripper` (the joint, its actuator and the equality),
   the gripper name the twin uses for every arm. The second jaw stays `gripper_finger_joint2`,
   coupled by the equality. Keyframe `home` unchanged.
2. Actuators are named after their joints (`arm_joint1..6`, `gripper`): the twin's scene finds an
   actuator by its joint name (`sim/urdf2mjcf.py` names them `arm1..arm6`, `gripper_finger1`).
3. The curled jaw tips (the collision box at the end of each jaw) are named `finger1_tip` /
   `finger2_tip`: `robot.yaml` names them as `fingertips`.
4. `<option integrator="implicitfast" timestep="0.002" cone="elliptic" impratio="10"/>`: the step
   of `sim/scene.xml`, cone and impratio as the SO-101 in MuJoCo Menagerie. The twin's scene copies
   the options of the arm model. `noslip_iterations` is left out on purpose: the scene does not copy
   it and MuJoCo Warp does not support it.
5. Site `tcp` as `sim/urdf2mjcf.py` makes it (x = approach, y = jaw closing), not rotated;
   `robot.yaml` gives the axes as `tcp_approach` / `tcp_closing`.
6. The equality coupling the jaws is stiffer than the default: `solref="0.01 1"`,
   `solimp="0.99 0.999 0.001 0.5 2"`. The real A1X gripper is one stiff degree of freedom (the
   driver publishes the second jaw as the mirror of the first). The default equality (solref 0.02,
   solimp 0.9/0.95) held the second jaw only softly: with violent arm actions in RL (5 ms step) and
   table contacts the jaws drifted apart by up to 36 mm. 0.01 s is the shortest time constant
   MuJoCo uses at a 5 ms step (refsafe: 2 x step), so a shorter one changes nothing; the 0.99-0.999
   impedance does the rest (worst about 12 mm, usually 2-5 mm).

The meshes are not copied: the model points at `galaxeo/arm/assets/meshes`, byte-identical to the
description package's. The output depends only on the URDF, so a rerun gives the same file byte
for byte (`tests/test_robot_a1x_model.py` checks it).
"""

from __future__ import annotations

import argparse
import os
import xml.etree.ElementTree as ET
from dataclasses import dataclass
from pathlib import Path
from xml.dom import minidom

REPO = Path(__file__).resolve().parent
URDF = REPO / "ros2_ws" / "src" / "galaxea_a1xy_description" / "urdf" / "a1x.urdf"
OUT = REPO / "galaxeo" / "robot" / "a1x" / "a1x.xml"
#: Relative to the model's folder: the meshes `galaxeo.arm` ships.
MESHDIR = "../../arm/assets/meshes"

# Position-servo gains: stiff enough to hold the pose under gravity.
KP = {"arm_joint1": 300, "arm_joint2": 600, "arm_joint3": 400,
      "arm_joint4": 150, "arm_joint5": 100, "arm_joint6": 60}
KP_GRIPPER = 1000


@dataclass(frozen=True)
class CollisionBox:
    pos: tuple[float, float, float]
    half: tuple[float, float, float]
    name: str | None = None


def _mirrored(box: CollisionBox, name: str | None) -> CollisionBox:
    x, y, z = box.pos
    return CollisionBox(pos=(x, -y, -z), half=box.half, name=name)


# Boxes instead of the jaw meshes: MuJoCo collides meshes as convex hulls, and an L-shaped jaw
# hulls into a wedge with a slanted inner face that squeezes a grasped object out. In the jaw body
# frame: the carriage behind the palm, the plate parallel to the other jaw, and the inward-curled
# tip (rule 3). Jaw 2 is the mirror image (y, z -> -y, -z).
FINGER1_BOXES = (
    CollisionBox(pos=(-0.047, -0.0385, 0.017), half=(0.007, 0.027, 0.006)),
    CollisionBox(pos=(0.017, -0.0015, 0.0), half=(0.024, 0.0015, 0.010)),
    CollisionBox(pos=(0.038, -0.0085, 0.0), half=(0.004, 0.0035, 0.006), name="tip"),
)
FINGER_COLLISION = {
    "gripper_finger_link1": [CollisionBox(b.pos, b.half, b.name and "finger1_tip") for b in FINGER1_BOXES],
    "gripper_finger_link2": [_mirrored(b, b.name and "finger2_tip") for b in FINGER1_BOXES],
}
HOME = {"arm_joint2": 1.0, "arm_joint3": -1.6, "arm_joint4": 0.6, "gripper_finger_joint1": 0.03}
#: Rule 1.
RENAME = {"gripper_finger_joint1": "gripper"}
#: Rule 4.
OPTION = {"integrator": "implicitfast", "timestep": "0.002", "cone": "elliptic", "impratio": "10"}
#: Rule 6.
MIRROR_SOLREF = "0.01 1"
MIRROR_SOLIMP = "0.99 0.999 0.001 0.5 2"
MIRRORED_JAW = "gripper_finger_joint2"

HEADER = """<!-- Generated by import_twin_model.py from {urdf} (Galaxea A1X vendor URDF,
     the same path as sim/urdf2mjcf.py). Do not edit by hand.
     Post-processing rules:
     1. joint gripper_finger_joint1 -> gripper (joint, actuator, equality); keyframe home unchanged
     2. actuators named exactly like their joints
     3. curled finger-tip collision boxes named finger1_tip / finger2_tip
     4. option: implicitfast, timestep 0.002, cone elliptic, impratio 10 (no noslip_iterations)
     5. site tcp as generated: x = approach, y = jaw closing
     6. jaw mirror equality stiffened: solref 0.01 1, solimp 0.99 0.999 0.001 0.5 2 -->
"""


@dataclass(frozen=True)
class LimitedJoint:
    """A URDF joint with a `<limit>`, in URDF order: the order of qpos and of the actuators."""

    name: str
    lower: float
    upper: float
    effort: float


def fmt(values) -> str:
    return " ".join(f"{float(x):.6g}" for x in values)


def generate(urdf: Path) -> str:
    """The MJCF text for `urdf`, not written anywhere."""
    robot = ET.parse(urdf).getroot()
    links = {link.get("name"): link for link in robot.findall("link")}
    joints = robot.findall("joint")
    children: dict[str, list[ET.Element]] = {}
    for j in joints:
        children.setdefault(j.find("parent").get("link"), []).append(j)
    child_links = {j.find("child").get("link") for j in joints}
    root_link = next(n for n in links if n not in child_links)

    mj = ET.Element("mujoco", model=robot.get("name"))
    ET.SubElement(mj, "compiler", angle="radian", eulerseq="XYZ", meshdir=MESHDIR, autolimits="true")
    ET.SubElement(mj, "option", OPTION)

    default = ET.SubElement(mj, "default")
    ET.SubElement(default, "joint", armature="0.01", damping="1")
    ET.SubElement(default, "position", forcelimited="true")
    d_vis = ET.SubElement(default, "default", {"class": "visual"})
    ET.SubElement(d_vis, "geom", type="mesh", contype="0", conaffinity="0", group="2")
    d_col = ET.SubElement(default, "default", {"class": "collision"})
    ET.SubElement(d_col, "geom", type="mesh", group="3")

    asset = ET.SubElement(mj, "asset")
    meshes: set[str] = set()
    world = ET.SubElement(mj, "worldbody")
    actuators = ET.SubElement(mj, "actuator")
    equality = ET.SubElement(mj, "equality")
    limited: list[LimitedJoint] = []

    def add_link(parent_el, link_name, pos="0 0 0", euler="0 0 0", joint=None):
        link = links[link_name]
        body = ET.SubElement(parent_el, "body", name=link_name, pos=pos)
        if euler != "0 0 0":
            body.set("euler", euler)

        if joint is not None:
            lim = joint.find("limit")
            j = ET.SubElement(body, "joint", name=RENAME.get(joint.get("name"), joint.get("name")),
                              type="hinge" if joint.get("type") == "revolute" else "slide",
                              axis=joint.find("axis").get("xyz"))
            if lim is not None:
                j.set("range", f'{lim.get("lower")} {lim.get("upper")}')
                limited.append(LimitedJoint(name=joint.get("name"), lower=float(lim.get("lower")),
                                            upper=float(lim.get("upper")), effort=float(lim.get("effort"))))

        inr = link.find("inertial")
        if inr is not None:
            o = inr.find("origin")
            assert o is None or o.get("rpy", "0 0 0").split() == ["0", "0", "0"], link_name
            i = inr.find("inertia")
            ET.SubElement(body, "inertial",
                          pos=o.get("xyz") if o is not None else "0 0 0",
                          mass=inr.find("mass").get("value"),
                          fullinertia=" ".join(i.get(k) for k in ("ixx", "iyy", "izz", "ixy", "ixz", "iyz")))

        for cls in ("visual", "collision"):
            if cls == "collision" and link_name in FINGER_COLLISION:
                for box in FINGER_COLLISION[link_name]:
                    attrs = {"class": "collision"}
                    if box.name:
                        attrs["name"] = box.name
                    ET.SubElement(body, "geom", attrs, type="box", pos=fmt(box.pos), size=fmt(box.half))
                continue
            for el in link.findall(cls):
                mesh = el.find("geometry/mesh")
                if mesh is None:
                    continue
                fname = os.path.basename(mesh.get("filename"))
                mname = os.path.splitext(fname)[0]
                if fname not in meshes:
                    meshes.add(fname)
                    ET.SubElement(asset, "mesh", name=mname, file=fname)
                g = ET.SubElement(body, "geom", {"class": cls}, mesh=mname)
                o = el.find("origin")
                if o is not None and o.get("xyz", "0 0 0") != "0 0 0":
                    g.set("pos", o.get("xyz"))
                if o is not None and o.get("rpy", "0 0 0") != "0 0 0":
                    g.set("euler", o.get("rpy"))
                color = el.find("material/color")
                if cls == "visual" and color is not None:
                    g.set("rgba", color.get("rgba"))

        if link_name == "gripper_link":
            # Between the jaw plates where they run parallel (plates at x = 0.03..0.06, the tips
            # curl inward at x = 0.078). Rule 5.
            ET.SubElement(body, "site", name="tcp", pos="0.045 0 0", size="0.005",
                          rgba="1 0 0 0.5", group="4")

        for cj in children.get(link_name, []):
            o = cj.find("origin")
            add_link(body, cj.find("child").get("link"),
                     pos=o.get("xyz", "0 0 0") if o is not None else "0 0 0",
                     euler=o.get("rpy", "0 0 0") if o is not None else "0 0 0",
                     joint=None if cj.get("type") == "fixed" else cj)

    add_link(world, root_link)

    # One position servo per arm joint and one for the gripper; the second jaw follows through the
    # equality below. Rule 2.
    for joint in limited:
        if joint.name == MIRRORED_JAW:
            continue
        kp = KP_GRIPPER if joint.name == "gripper_finger_joint1" else KP[joint.name]
        mj_name = RENAME.get(joint.name, joint.name)
        ET.SubElement(actuators, "position", name=mj_name, joint=mj_name, kp=str(kp), kv=str(kp / 20),
                      ctrlrange=fmt((joint.lower, joint.upper)), forcerange=fmt((-joint.effort, joint.effort)))
    ET.SubElement(equality, "joint", joint1=MIRRORED_JAW,
                  joint2=RENAME["gripper_finger_joint1"], polycoef="0 -1 0 0 0",
                  solref=MIRROR_SOLREF, solimp=MIRROR_SOLIMP)

    # Keyframe "home": raised, so the arm does not lie on its own base.
    qpos = [HOME.get(joint.name, 0.0) for joint in limited]
    names = [joint.name for joint in limited]
    qpos[names.index(MIRRORED_JAW)] = -HOME["gripper_finger_joint1"]
    ctrl = [HOME.get(joint.name, 0.0) for joint in limited if joint.name != MIRRORED_JAW]
    kf = ET.SubElement(mj, "keyframe")
    ET.SubElement(kf, "key", name="home", qpos=fmt(qpos), ctrl=fmt(ctrl))

    xml = minidom.parseString(ET.tostring(mj)).toprettyxml(indent="  ")
    xml = xml.replace('<?xml version="1.0" ?>\n', "")
    return HEADER.format(urdf=urdf.name) + xml


def main(argv: list[str] | None = None) -> int:
    ap = argparse.ArgumentParser(description="The twin's A1X model (MJCF) from the vendor URDF.")
    ap.add_argument("--urdf", type=Path, default=URDF, help="vendor URDF")
    ap.add_argument("--out", type=Path, default=OUT, help="MJCF file to write")
    args = ap.parse_args(argv)

    args.out.write_text(generate(args.urdf), encoding="utf-8", newline="\n")
    print(f"wrote {args.out}")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
